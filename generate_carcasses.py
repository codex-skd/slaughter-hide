    for mob_id, const_name, entity_type, has_head, has_head_mount, has_skeleton, skin_item, meat_item in MOB_INFO:
        data = SHAPES[mob_id]
        
        # Shape methods
        output.append(f"// Shapes below are ported 1:1 from the original Butchery {mob_id} blocks.")
        output.append(gen_shape_method(mob_id, "hanging", data))
        output.append("")
        output.append(gen_shape_method(mob_id, "lying", data))
        output.append("")
        if has_head:
            output.append(gen_shape_method(mob_id, "head", data))
            output.append("")
        if has_head_mount:
            output.append(gen_shape_method(mob_id, "head_mount", data))
            output.append("")
        if has_skeleton:
            output.append(f"    private static VoxelShape {mob_id}SkeletonHanging(BlockState state) {{")
            output.append(f"        return {mob_id}Hanging(state);")
            output.append(f"    }}")
            output.append("")
            output.append(f"    private static VoxelShape {mob_id}SkeletonLying(BlockState state) {{")
            output.append(f"        return {mob_id}Lying(state);")
            output.append(f"    }}")
            output.append("")
        else:
            output.append(f"    // {mob_id} has no skeleton")
            output.append("")
        
        output.append(gen_build_method(mob_id, const_name, entity_type, has_head, has_head_mount, has_skeleton, skin_item, meat_item))
        output.append("")
    
    print("\n".join(output))

