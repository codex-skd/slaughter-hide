def format_box(b):
    """Format a box tuple as box(x1, y1, z1, x2, y2, z2)"""
    if b[0] == "box":
        return f"box({b[1]}, {b[2]}, {b[3]}, {b[4]}, {b[5]}, {b[6]})"
    return str(b)

def format_shape_list(boxes):
    """Format a list of boxes for a facing direction."""
    if len(boxes) == 1:
        return format_box(boxes[0])
    elif len(boxes) == 2:
        return f"Shapes.or({format_box(boxes[0])}, {format_box(boxes[1])})"
    elif len(boxes) == 3:
        return f"Shapes.or({format_box(boxes[0])}, {format_box(boxes[1])}, {format_box(boxes[2])})"
    elif len(boxes) == 4:
        return f"Shapes.or({format_box(boxes[0])}, {format_box(boxes[1])}, {format_box(boxes[2])}, {format_box(boxes[3])})"
    elif len(boxes) == 5:
        return f"Shapes.or({format_box(boxes[0])}, {format_box(boxes[1])}, {format_box(boxes[2])}, {format_box(boxes[3])}, {format_box(boxes[4])})"
    else:
        parts = ", ".join(format_box(b) for b in boxes)
        return f"Shapes.or({parts})"

def gen_shape_method(mob_id, shape_type, data):
    """Generate a static VoxelShape method."""
    # Fix naming: head_mount -> HeadMount, etc.
    if shape_type == "head_mount":
        method_name = f"{mob_id}HeadMount"
    elif shape_type == "head":
        method_name = f"{mob_id}Head"
    else:
        method_name = f"{mob_id}{shape_type.capitalize()}"
    if shape_type in ("skeleton_hanging", "skeleton_lying"):
        return None  # handled separately
    
    lines = [f"    private static VoxelShape {method_name}(BlockState state) {{",
             f"        return switch (state.getValue(CarcassBlockProperty.FACING)) {{"]
    
    facings = ["NORTH", "EAST", "WEST", "SOUTH"]
    for i, facing in enumerate(facings):
        boxes = data[shape_type].get(facing, [])
        if boxes:
            shape_expr = format_shape_list(boxes)
        else:
            shape_expr = "Shapes.empty()"
        if facing == "SOUTH":
            lines.append(f"            default -> {shape_expr};")
        else:
            lines.append(f"            case {facing} -> {shape_expr};")
    
    lines.append("        };")
    lines.append("    }")
    return "\n".join(lines)

def gen_build_method(mob_id, const_name, entity_type, has_head, has_head_mount, has_skeleton, skin_item, meat_item):
    """Generate the buildXxx() method."""
    lines = [f"    private static CarcassDefinition build{const_name}() {{",
             f"        return new CarcassDefinition(",
             f"                \"{mob_id}\",",
             f"                BuiltInRegistries.ENTITY_TYPE.getOrThrow(",
             f"                                ResourceKey.create(Registries.ENTITY_TYPE, Identifier.parse(\"{entity_type}\")))",
             f"                        .value(),",
             f"                {str(has_head).lower()},",
             f"                {str(has_head_mount).lower()},",
             f"                {str(has_skeleton).lower()},",
             f"                state -> state.getValue(CarcassBlockProperty.BLOCKSTATE) == 1 ? {mob_id}Hanging(state) : {mob_id}Lying(state),",
             f"                Carcasses::{mob_id}Lying,"]
    
    if has_head:
        lines.append(f"                Carcasses::{mob_id}Head,")
    else:
        lines.append(f"                Carcasses::{mob_id}Lying,  // no head")
    
    if has_head_mount:
        lines.append(f"                Carcasses::{mob_id}HeadMount,")
    else:
        lines.append(f"                Carcasses::{mob_id}Lying,  // no head mount")
    
    if has_skeleton:
        lines.append(f"                state -> state.getValue(CarcassBlockProperty.BLOCKSTATE) == 1 ? {mob_id}SkeletonHanging(state) : {mob_id}SkeletonLying(state),")
    else:
        lines.append(f"                Carcasses::{mob_id}Lying,  // no skeleton")
    
    if meat_item.startswith("minecraft:"):
        lines.append(f"                // {mob_id} drops {meat_item}")
        lines.append(f"                java.util.List.of(net.minecraft.world.item.Items.{meat_item.split(':')[1].upper()}));")
    else:
        lines.append(f"                // {mob_id} drops {meat_item}")
        lines.append(f"                java.util.List.of(ModItems.{meat_item.upper()}));")
    
    lines.append("    }")
    return "\n".join(lines)

